import AICore
import AppKit

/// Types text into the frontmost app through the general pasteboard and synthesized ⌘V, the
/// technique text expanders use, since no API inserts text into another app's field; pasting
/// rather than posting characters keeps a newline from sending a chat message and keeps editors'
/// auto-pairing and input methods out of it. With the user's typing setting on, the text arrives
/// in ``TypingPace`` chunks, each sized when it is due and pasted once the field's caret showed
/// the one before in (``PasteProgress``, ``FieldCaret``); a field whose caret cannot be read, or
/// whose selection was read by copying (``WriteTarget/Selection/copied``), gets the text in one
/// paste, confirmed by its read (``PasteHandshake``). ``TypingPace`` owns the
/// clock: every step, the field's first caret read and each confirmation included, counts against
/// its budget and deadline, so the last character is in within two seconds of the start, however
/// long the text or slow the field. At most one ⌘V is ever outstanding. Items stay on this Mac (no
/// Universal Clipboard) and carry the nspasteboard.org transient and auto-generated types so
/// clipboard managers skip them; the user's own pasteboard comes back once the last chunk is
/// confirmed in.
enum ClipboardPaste {
  private static let markers: [NSPasteboard.PasteboardType] = [
    .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
  ]
  /// How long the field gets to report its selection before the first chunk; the time it takes
  /// counts against the typing budget.
  private static let caretLimit: Duration = .milliseconds(500)
  /// How long the pasteboard keeps a chunk confirmed only by its read before the user's items
  /// return: the read may have been another process's, and the target's ⌘V still due.
  private static let readGrace: Duration = .milliseconds(100)

  /// Types `text` into `target`'s app, which must be frontmost with the field restored for
  /// `mode`, as `typing`, the user's typing setting, says (all at once when it is off, under
  /// reduced motion or where the caret cannot be followed). Nil once every chunk is in; `failed`
  /// when the first chunk did not go in within its limit; `interrupted` when the user pressed a key
  /// or a mouse button or another app came forward, or a later chunk did not go in within its
  /// limit, so only the beginning of the text arrived.
  /// A chunk that never went in stays on the pasteboard, so a ⌘V the target handles late pastes
  /// it rather than the user's items; the page puts the whole text there after every failure.
  static func type(
    _ text: String, into target: WriteTarget, mode: TextWriteParams.Mode, typing: Bool
  ) async -> TextWriteResult.NotOk.Reason? {
    let start = ContinuousClock.now
    let caret = FieldCaret(target: target)
    // A copied selection has no range: the app's own selection says where the text goes, so its
    // caret is not followed.
    var progress: PasteProgress?
    if case .field(range: .some) = target.selection {
      progress = await caret.progress(mode: mode, within: caretLimit)
    }
    let tracked = progress != nil
    var pace = TypingPace(
      text, typing: typing,
      reduceMotion: NSWorkspace.shared.accessibilityDisplayShouldReduceMotion,
      caretTracked: tracked)
    let pasteboard = NSPasteboard.general
    let saved = PasteboardSnapshot(of: pasteboard)
    let handshake = PasteHandshake()
    let input = UserInputWatch()
    input.start()
    defer { input.stop() }
    let pasteKey = KeyPress.pasteKeyCode()
    var written: Int?
    var outcome: TextWriteResult.NotOk.Reason?
    var index = 0
    while let chunk = pace.next(at: .now - start) {
      if start + chunk.due > .now { try? await Task.sleep(until: start + chunk.due) }
      guard !input.acted, NSWorkspace.shared.frontmostApplication?.processIdentifier == target.pid
      else {
        outcome = .interrupted
        break
      }
      written = write(handshake.promise(chunk.text, index: index), to: pasteboard)
      KeyPress.post(pasteKey, flags: .maskCommand)
      let limit = TypingPace.confirmationLimit(for: chunk, pastedAt: .now - start)
      let missed: TextWriteResult.NotOk.Reason = index == 0 ? .failed : .interrupted
      if let current = progress {
        guard let next = await confirm(chunk.text, from: current, by: caret, within: limit)
        else { return missed }
        progress = next
      } else {
        guard await handshake.read(index, within: limit) else { return missed }
      }
      index += 1
    }
    guard let written else { return outcome }
    // The caret proves the target's last ⌘V ran and no other is pending; a read does not.
    if !tracked { try? await Task.sleep(for: readGrace) }
    // Something the user copied meanwhile stays.
    if pasteboard.changeCount == written { saved.restore(to: pasteboard) }
    return outcome
  }

  /// The progress after `chunk`, once the caret shows it in within `limit`; nil when it does not.
  private static func confirm(
    _ chunk: String, from progress: PasteProgress, by caret: FieldCaret, within limit: Duration
  ) async -> PasteProgress? {
    guard let location = await caret.wait(atLeast: progress.threshold(for: chunk), within: limit)
    else { return nil }
    var next = progress
    return next.confirm(chunk, caretAt: location) ? next : nil
  }

  /// Replaces the pasteboard with one marked item whose string `provider` supplies when read,
  /// kept to this Mac so Universal Clipboard neither reads nor syncs it, and returns the
  /// pasteboard's change count after the write.
  private static func write(
    _ provider: NSPasteboardItemDataProvider, to pasteboard: NSPasteboard
  ) -> Int {
    let item = NSPasteboardItem()
    item.setDataProvider(provider, forTypes: [.string])
    for marker in markers { item.setData(Data(), forType: marker) }
    pasteboard.prepareForNewContents(with: .currentHostOnly)
    pasteboard.writeObjects([item])
    return pasteboard.changeCount
  }
}

/// Notices the user pressing a key or a mouse button while text is arriving, which stops the
/// typing. The ⌘V presses ``KeyPress`` synthesizes are not the user's. A global monitor misses
/// events that go to Atd itself; Atd coming forward fails the frontmost check instead.
private final class UserInputWatch {
  private(set) var acted = false
  private var monitor: Any?

  func start() {
    monitor = NSEvent.addGlobalMonitorForEvents(
      matching: [.keyDown, .leftMouseDown, .rightMouseDown, .otherMouseDown]
    ) { [weak self] event in
      guard !KeyPress.isSynthesized(event) else { return }
      MainActor.assumeIsolated { self?.acted = true }
    }
  }

  func stop() {
    if let monitor { NSEvent.removeMonitor(monitor) }
    monitor = nil
  }
}
