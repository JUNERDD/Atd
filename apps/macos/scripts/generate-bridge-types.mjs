// Generates Swift Codable types from TypeBox contracts:
// - the native bridges, from the JSON Schemas apps/desktop/scripts/export-bridge-schema.mjs
//   exports: the renderer's (native-bridge.schema.json → Sources/AICore/Bridge/Generated) and the
//   user apps' `atdApp` bridge (user-app-bridge.schema.json → Sources/AICore/UserApps/Generated),
//   each into its own files so the shell's two dispatchers never share message types;
// - the desktop widgets' view tree and sync payload, read straight from
//   packages/agent-contracts (widget-schema.mjs → Sources/AIWidgetModel/Generated), which the
//   shell and the WidgetKit extension share.
// `--check` regenerates into memory and fails when the checked-in files differ.
//
//   node scripts/generate-bridge-types.mjs          write the Generated/*.swift files
//   node scripts/generate-bridge-types.mjs --check  exit 1 when those files are stale
//
// quicktype was evaluated first and rejected: it merges every discriminated union (the call and
// event envelopes, `CaptureResult`, `SocketFrame`) into one struct of optionals and its Swift 6
// output does not compile (`JSONAny` is not Sendable). This script covers exactly the TypeBox
// subset the contracts use and fails on anything else, so a contract change it cannot express is
// caught here rather than generated wrongly. Layout is left to `swift format`.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { emitEnvelopes } from './bridge-envelopes.mjs';
import { createEmitter } from './bridge-emitter.mjs';
import { emitUserAppEnvelopes } from './user-app-envelopes.mjs';
import { widgetSchema, widgetSections } from './widget-schema.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const schemaDir = path.resolve(root, '../desktop/src/native-bridge');
/** Files stay well below the repository's 350-line limit once formatted. */
const lineBudget = 260;
const header = ({ source, rerun, imports = ['Foundation'] }) =>
  [
    '// Generated by apps/macos/scripts/generate-bridge-types.mjs from',
    `// ${source}. Do not edit; run`,
    `// ${rerun}.`,
    '',
    ...imports.map((name) => `import ${name}`),
    '',
  ].join('\n');
const bridgeRerun =
  '`pnpm --filter @atd/macos codegen` after `pnpm --filter @atd/desktop bridge-schema`';

/** `window.setPinned` → `WindowSetPinned`, as the schema export names its definitions. */
const pascal = (name) =>
  name
    .split(/[.\s_-]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

function section(emitter, defs, title, entries) {
  return {
    title,
    blocks: entries.map(([name, doc]) => emitter.definition(name, defs[name], doc)),
  };
}

/** The renderer bridge (`aiNative`), which also emits the `NativeEmpty` both bridges share. */
function rendererSections(schema) {
  const bridge = schema['x-bridge'];
  const defs = schema.$defs;
  /** Definitions other schemas reuse; an equal inline schema refers to them by name. */
  const shared = ['FileRef', 'ShortcutRegistration', 'ShortcutResult', 'SocketFrame'];
  const emitter = createEmitter({ defs, shared });
  return [
    section(
      emitter,
      defs,
      'Shared',
      shared.map((name) => [name]),
    ),
    section(
      emitter,
      defs,
      'Calls',
      bridge.calls.flatMap((method) => [
        [`${pascal(method)}Params`, `Params of the \`${method}\` call.`],
        [`${pascal(method)}Result`, `Result of the \`${method}\` call.`],
      ]),
    ),
    section(
      emitter,
      defs,
      'Posts',
      bridge.posts.map((method) => [`${pascal(method)}Post`, `Params of the \`${method}\` post.`]),
    ),
    section(
      emitter,
      defs,
      'Events',
      bridge.events.map((event) => [`${pascal(event)}Event`, `Payload of the \`${event}\` event.`]),
    ),
    {
      title: 'Messages',
      blocks: [
        emitter.constants(bridge),
        emitter.empty(),
        ...emitEnvelopes({ defs, bridge, pascal, emitter }),
      ],
    },
  ];
}

/** The user app bridge (`atdApp`): `UserApp`-prefixed types beside the renderer's. */
function userAppSections(schema) {
  const bridge = schema['x-bridge'];
  const defs = schema.$defs;
  const emitter = createEmitter({ defs, shared: ['UserAppFile'] });
  return [
    section(
      emitter,
      defs,
      'Calls',
      [['UserAppFile', 'A picked file: its name and bytes.']].concat(
        bridge.calls.flatMap((method) => [
          [`UserApp${pascal(method)}Params`, `Params of the \`${method}\` call.`],
          [`UserApp${pascal(method)}Result`, `Result of the \`${method}\` call.`],
        ]),
      ),
    ),
    section(
      emitter,
      defs,
      'Posts',
      bridge.posts.map((method) => [
        `UserApp${pascal(method)}Post`,
        `Params of the \`${method}\` post.`,
      ]),
    ),
    { title: 'Messages', blocks: emitUserAppEnvelopes({ defs, bridge, pascal }) },
  ];
}

const targets = [
  {
    schema: () => readSchema('native-bridge.schema.json'),
    source: 'apps/desktop/src/native-bridge/native-bridge.schema.json',
    rerun: bridgeRerun,
    outputDir: path.join(root, 'Sources/AICore/Bridge/Generated'),
    filePrefix: 'Bridge',
    sections: rendererSections,
  },
  {
    schema: () => readSchema('user-app-bridge.schema.json'),
    source: 'apps/desktop/src/native-bridge/user-app-bridge.schema.json',
    rerun: bridgeRerun,
    outputDir: path.join(root, 'Sources/AICore/UserApps/Generated'),
    filePrefix: 'UserAppBridge',
    sections: userAppSections,
  },
  {
    schema: widgetSchema,
    source: 'packages/agent-contracts/src/widgets.ts and widget-sync.ts',
    rerun: '`pnpm --filter @atd/macos codegen` after changing them',
    imports: ['AICore', 'Foundation'],
    outputDir: path.join(root, 'Sources/AIWidgetModel/Generated'),
    filePrefix: 'Widget',
    sections: widgetSections,
  },
];

function readSchema(name) {
  return JSON.parse(readFileSync(path.join(schemaDir, name), 'utf8'));
}

/** Packs a section's blocks into files under the line budget, split at definition boundaries. */
async function files(target) {
  const { filePrefix, sections } = target;
  const schema = await target.schema();
  const result = new Map();
  for (const { title, blocks } of sections(schema)) {
    const chunks = [[]];
    let lines = 0;
    for (const block of blocks.filter(Boolean)) {
      const size = block.split('\n').length + 1;
      if (lines > 0 && lines + size > lineBudget) {
        chunks.push([]);
        lines = 0;
      }
      chunks.at(-1).push(block);
      lines += size;
    }
    chunks.forEach((chunk, index) => {
      const name = `${filePrefix}${title}${chunks.length > 1 ? index + 1 : ''}.swift`;
      result.set(name, `${header(target)}${chunk.join('\n\n')}\n`);
    });
  }
  return result;
}

/** Formats generated sources with the package's own swift-format configuration. */
function format(sources) {
  const dir = mkdtempSync(path.join(tmpdir(), 'bridge-types-'));
  try {
    for (const [name, text] of sources) writeFileSync(path.join(dir, name), text);
    execFileSync(
      'swift',
      [
        'format',
        'format',
        '--in-place',
        '--configuration',
        path.join(root, '.swift-format'),
        ...[...sources.keys()].map((name) => path.join(dir, name)),
      ],
      { stdio: 'inherit' },
    );
    const formatted = new Map();
    for (const name of sources.keys()) {
      const text = readFileSync(path.join(dir, name), 'utf8');
      const count = text.split('\n').length - 1;
      if (count > 350) throw new Error(`${name} has ${count} lines; lower lineBudget.`);
      formatted.set(name, text);
    }
    return formatted;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function checkedIn(outputDir) {
  const current = new Map();
  let names = [];
  try {
    names = readdirSync(outputDir).filter((name) => name.endsWith('.swift'));
  } catch {
    // A missing directory is stale as well.
  }
  for (const name of names) current.set(name, readFileSync(path.join(outputDir, name), 'utf8'));
  return current;
}

for (const target of targets) {
  const { outputDir } = target;
  const generated = format(await files(target));
  if (process.argv.includes('--check')) {
    if (
      !isDeepStrictEqual(Object.fromEntries(checkedIn(outputDir)), Object.fromEntries(generated))
    ) {
      console.error(
        `${outputDir} is out of date with the bridge schema. Run: pnpm --filter @atd/macos codegen`,
      );
      process.exit(1);
    }
  } else {
    rmSync(outputDir, { recursive: true, force: true });
    mkdirSync(outputDir, { recursive: true });
    for (const [name, text] of generated) writeFileSync(path.join(outputDir, name), text);
    console.log(`Wrote ${generated.size} files to ${path.relative(root, outputDir)}.`);
  }
}
