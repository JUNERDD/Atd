// Brings the model providers' brand marks to the shell: each mark in packages/ui/src/assets/brands
// becomes an image set under App/Assets.xcassets/ProviderBrands (`brand-<stem>`, vector, a template
// for a monochrome mark so it follows the label colour), and providers.json's provider-to-mark table
// becomes ProviderBrands.swift. The renderer reads the same table
// (apps/desktop/src/features/providers/provider-brand.tsx), so both draw the same mark.
// `--check` compares instead of writing and fails when the checked-in output is stale.
//
//   node scripts/provider-brands.mjs          write the image sets and the Swift table
//   node scripts/provider-brands.mjs --check  exit 1 when they are stale
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const brandRoot = path.resolve(root, '../../packages/ui/src/assets/brands');
const catalog = path.join(root, 'App/Assets.xcassets/ProviderBrands');
const swiftFile = path.join(root, 'Sources/AICore/ProviderBrands/ProviderBrands.swift');
const check = process.argv.includes('--check');

const table = JSON.parse(readFileSync(path.join(brandRoot, 'providers.json'), 'utf8'));
/** Every mark by file stem; stems are unique across the brand folders. */
const marks = new Map();
for (const folder of ['.', 'lndev', 'external'])
  for (const file of readdirSync(path.join(brandRoot, folder)).sort())
    if (file.endsWith('.svg')) {
      const stem = file.slice(0, -4);
      if (marks.has(stem)) throw new Error(`Two brand marks are named ${stem}.`);
      marks.set(stem, path.join(brandRoot, folder, file));
    }
for (const stem of [
  ...Object.values(table.providers),
  ...Object.values(table.prefixes),
  ...Object.values(table.inline),
  ...table.monochrome,
])
  if (!marks.has(stem)) throw new Error(`providers.json names a missing mark: ${stem}.`);

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const info = { author: 'xcode', version: 1 };
/** Relative path → contents, for every file the catalog folder should hold. */
const files = new Map([['Contents.json', json({ info })]]);
for (const [stem, source] of marks) {
  const set = `brand-${stem}.imageset`;
  files.set(`${set}/${stem}.svg`, readFileSync(source, 'utf8'));
  files.set(
    `${set}/Contents.json`,
    json({
      images: [{ filename: `${stem}.svg`, idiom: 'universal' }],
      info,
      properties: {
        'preserves-vector-representation': true,
        'template-rendering-intent': table.monochrome.includes(stem) ? 'template' : 'original',
      },
    }),
  );
}

const literal = (value) => JSON.stringify(value);
const entries = (object) =>
  Object.entries(object)
    .map(([key, value]) => `    ${literal(key)}: ${literal(value)},`)
    .join('\n');
const swift = `// Generated by apps/macos/scripts/provider-brands.mjs from
// packages/ui/src/assets/brands/providers.json. Do not edit; run
// \`pnpm --filter @atd/macos codegen\`.

import Foundation

/// The brand mark a model provider shows inline, as the renderer's \`ProviderBrand\` picks it.
public enum ProviderBrands {
  /// The asset catalog image (\`brand-<mark>\`) for \`provider\`, or nil when it has no mark.
  public static func asset(for provider: String) -> String? {
    let mark =
      inline[provider] ?? providers[provider]
      ?? prefixes.first { provider.hasPrefix($0.prefix) }?.mark ?? provider
    return marks.contains(mark) ? "brand-\\(mark)" : nil
  }

  private static let providers: [String: String] = [
${entries(table.providers)}
  ]
  private static let prefixes: [(prefix: String, mark: String)] = [
${Object.entries(table.prefixes)
  .map(([prefix, mark]) => `    (${literal(prefix)}, ${literal(mark)}),`)
  .join('\n')}
  ]
  private static let inline: [String: String] = [
${entries(table.inline)}
  ]
  private static let marks: Set<String> = [
${[...marks.keys()].map((stem) => `    ${literal(stem)},`).join('\n')}
  ]
}
`;

const stale = [];
const present = (dir, prefix = '') =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
        entry.isDirectory()
          ? present(path.join(dir, entry.name), `${prefix}${entry.name}/`)
          : [`${prefix}${entry.name}`],
      )
    : [];
for (const file of present(catalog)) if (!files.has(file)) stale.push(`extra ${file}`);
for (const [file, contents] of files) {
  const target = path.join(catalog, file);
  if (!existsSync(target) || readFileSync(target, 'utf8') !== contents) stale.push(file);
}
if (!existsSync(swiftFile) || readFileSync(swiftFile, 'utf8') !== swift)
  stale.push(path.relative(root, swiftFile));

if (check) {
  if (stale.length > 0) {
    console.error(`Provider brand marks are stale (${stale.join(', ')}); run \`pnpm codegen\`.`);
    process.exit(1);
  }
} else if (stale.length > 0) {
  rmSync(catalog, { recursive: true, force: true });
  for (const [file, contents] of files) {
    mkdirSync(path.dirname(path.join(catalog, file)), { recursive: true });
    writeFileSync(path.join(catalog, file), contents);
  }
  mkdirSync(path.dirname(swiftFile), { recursive: true });
  writeFileSync(swiftFile, swift);
  console.log(`Wrote ${marks.size} provider brand marks.`);
}
