#!/usr/bin/env node
/**
 * Builds the Node-API addon from `crates/file-index-node` with `napi build --release` for the
 * host: darwin-arm64 and darwin-x64 are the targets (the index watches folders with FSEvents, and
 * the native app ships for macOS on both). Hosts other than macOS skip the build, and the loader
 * then throws, which the service reports as an unavailable search; `pnpm check` on Linux relies on
 * that skip. A Mac with any other architecture fails, as does a build that leaves no addon for
 * this Node's architecture (for example a Node running under Rosetta beside a native Rust).
 *
 * The addon lands here as `file-index.darwin-<arch>.node` (gitignored). The loader `index.js` and
 * the `index.d.ts` are generated by the same command and checked in, formatted with oxfmt, so
 * type checking works on hosts that skip the build.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

if (process.platform !== 'darwin') {
  process.stdout.write(
    `Skipping the file-index addon: it builds on macOS only, not ${process.platform}-${process.arch}.\n`,
  );
  process.exit(0);
}
if (!['arm64', 'x64'].includes(process.arch)) {
  process.stderr.write(
    `The file-index addon builds for darwin-arm64 and darwin-x64 only, not darwin-${process.arch}.\n`,
  );
  process.exit(1);
}

// napi names the addon after the Rust host it built for; this Node must be able to load it. A
// previous build's copy is removed first so that only this build can satisfy the check below.
const addon = `file-index.darwin-${process.arch}.node`;
rmSync(path.join(packageRoot, addon), { force: true });
const napi = spawnSync(
  'napi',
  [
    'build',
    '--release',
    '--platform',
    '--esm',
    '--manifest-path',
    '../../crates/file-index-node/Cargo.toml',
    '--output-dir',
    '.',
    '--js',
    'index.js',
    '--dts',
    'index.d.ts',
    // `Phase` becomes a string-literal union instead of a `const enum`, which the service's
    // isolated-modules compilation cannot import.
    '--no-const-enum',
  ],
  { cwd: packageRoot, stdio: 'inherit' },
);
if (napi.status !== 0) process.exit(napi.status ?? 1);
if (!existsSync(path.join(packageRoot, addon))) {
  process.stderr.write(
    `napi build left no ${addon}: the Rust toolchain built for another architecture than this Node (darwin-${process.arch}).\n`,
  );
  process.exit(1);
}
// Not `napi build --pipe`: that also pipes the binary through the command.
const format = spawnSync('oxfmt', ['index.js', 'index.d.ts'], {
  cwd: packageRoot,
  stdio: 'inherit',
});
process.exit(format.status ?? 1);
